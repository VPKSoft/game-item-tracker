/** Makes every leaf of a translation tree a plain string, so other languages can have any text. */
type DeepString<T> = { [K in keyof T]: T[K] extends string ? string : DeepString<T[K]> };

/** The shape every language must have. */
type Translation = DeepString<typeof en>;

